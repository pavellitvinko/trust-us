"""Cloaking differential, comparison side (HAC-15): signals J1, J5 and J2.

The variants of one URL (captured by `capture/differential.py`, one view per profile) are
compared with the pipeline's own text and structure comparators. The ad-click variant is
the reference: it is what the ad's audience saw.

- `cloak.differential` (J1), on the ad-click view, one row per other profile: the difference
  score and its parts. PRESENT at or above the threshold, ABSENT below it, NOT_OBSERVABLE
  when either variant did not load a page.
- `cloak.gating` (J5), on the ad-click view, when ad click and bare differ: the page is gated
  on what only the ad click carried (referrer, click id or query, device), read from what each
  capture recorded. The factors are listed; two profiles cannot tell which one the cloaker
  checks. Not asserted when bare got an HTTP error: a page that needs its query to exist
  (`product.php?id=…`) answers 404 without it, and that is not gating.
- `cloak.white_page` (J2), on a variant that differs from the ad click: the white-page traits
  it shows that the ad click does not (no trackers, obfuscated hash-like class names). Only
  computed inside a positive differential: on its own each trait fits many genuine pages.

All rows are RISK: they explain a view, they never link two views.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath
from typing import Any
from urllib.parse import urlsplit

from ..capture.profiles import SYNTHETIC_FBCLID
from ..compare.minhash import shingles
from ..contracts import Fingerprint, Observation, Purpose, Source, State, View
from ..layers._text import body_text
from ..layers.kit import _FRAMEWORK_CLASS_PREFIXES
from ..registry import comparators, load_plugins
from ..store import Store

EXTRACTOR = "cloak.differential"
VERSION = "1"
REFERENCE = "ad_click"
THRESHOLD = 0.5  # difference at or above this is recorded as cloaking
HOST_CHANGE_FLOOR = 0.9  # landing on another registrable domain is a difference by itself
MIN_SHINGLE_WORDS = 20  # below this, compare word sets: a white page can be short
HASH_CLASS_SHARE = 0.3  # share of hash-like class names that marks obfuscated markup
HASH_CLASS_MARGIN = 0.2  # ...and by how much it must exceed the ad click's own share
TRACKER_NAMESPACES = (
    "fb_pixel",
    "ga_id",
    "gtm_id",
    "gads_id",
    "gads_conversion",
    "taboola_id",
    "uet_id",
    "tiktok_pixel",
    "ym_id",
    "third_party.host",
)
# `a1a02dd7`, `_3xk9f2a`, `css-1q2w3e4`: generated names, not words a developer typed.
_HASH_CLASS = re.compile(r"^(?:[a-z]{1,4}[-_])?_?([a-z0-9]{6,})$", re.IGNORECASE)
# `mt20px`, `col12`, `h100vh`: a word, a number and a unit, written by hand.
_WORD_NUMBER = re.compile(r"^[a-z]+\d+[a-z]{0,3}$", re.IGNORECASE)
# `size-1024x768`, `banner300x250`: dimensions.
_DIMENSIONS = re.compile(r"\d+x\d+", re.IGNORECASE)
# Generated by mainstream CSS-in-JS, so they say nothing about a cloaker: Emotion, MUI and
# Chakra (`css-1ujsas3`), react-native-web (`r-18u37iz`), Meta StyleX (`x1n2onr6`).
_CSS_IN_JS = re.compile(r"^(?:css-|r-)[a-z0-9]+$|^x[a-z0-9]{4,9}$", re.IGNORECASE)


# --- small pure helpers (tested directly) ----------------------------------------------


def jaccard(a: set, b: set) -> float | None:
    if not a and not b:
        return None
    return len(a & b) / len(a | b)


def text_similarity(
    text_a: str, text_b: str, fp_a: Fingerprint | None = None, fp_b: Fingerprint | None = None
) -> float | None:
    """`text.shingle` MinHash when both views have it, else exact overlap of the same shingles
    (word sets for short text). None when neither variant has text."""
    if not text_a.strip() and not text_b.strip():
        return None
    if not text_a.strip() or not text_b.strip():
        return 0.0
    if fp_a is not None and fp_b is not None:
        return comparators.get("minhash").compare(fp_a, fp_b).score
    short = min(len(text_a.split()), len(text_b.split())) < MIN_SHINGLE_WORDS
    n = 1 if short else 5
    return jaccard(shingles(text_a, n), shingles(text_b, n))


def is_hash_like(name: str) -> bool:
    """A generated class name: letters and at least two digits mixed, not word+number+unit.

    Framework classes (the `kit.dom` list) and mainstream CSS-in-JS names are not counted.
    """
    if name.startswith(_FRAMEWORK_CLASS_PREFIXES) or _CSS_IN_JS.match(name):
        return False
    if _DIMENSIONS.search(name):
        return False
    match = _HASH_CLASS.match(name)
    if not match:
        return False
    core = match.group(1)
    digits = sum(ch.isdigit() for ch in core)
    return 2 <= digits < len(core) and not _WORD_NUMBER.match(core)


def difference_score(
    text_sim: float | None, structure_sims: list[float], hosts_differ: bool
) -> float | None:
    parts = [s for s in (text_sim, *structure_sims) if s is not None]
    if not parts and not hosts_differ:
        return None
    difference = 1 - sum(parts) / len(parts) if parts else 0.0
    if hosts_differ:
        difference = max(difference, HOST_CHANGE_FLOOR)
    return round(difference, 3)


# --- per-view facts ---------------------------------------------------------------------


def _list_values(observations: list[Observation], namespace: str) -> set[str]:
    out: set[str] = set()
    for o in observations:
        if o.namespace != namespace or o.state is not State.PRESENT:
            continue
        values = o.value if isinstance(o.value, list) else [o.value]
        out.update(str(v) for v in values if v not in (None, ""))
    return out


def _registrable(observations: list[Observation]) -> str | None:
    return next(
        (
            str(o.value)
            for o in observations
            if o.namespace == "domain.registrable" and o.state is State.PRESENT and o.value
        ),
        None,
    )


def _trackers(observations: list[Observation]) -> list[str]:
    return sorted(
        f"{o.namespace}:{o.value}"
        for o in observations
        if o.namespace in TRACKER_NAMESPACES and o.state is State.PRESENT and o.value
    )


class _Variant:
    def __init__(self, store: Store, view: View):
        self.view = view
        meta = view.meta
        self.profile = str(meta.get("capture_profile") or "")
        self.status = str(meta.get("capture_status") or "ok")
        self.url = str(meta.get("manifest_url") or "")
        self.referer = meta.get("capture_referer")
        self.user_agent = str(meta.get("capture_user_agent") or "")
        self.click_id_added = meta.get("capture_click_id_added") is True
        self.obs = store.observations(view.view_id)
        fps = {f.layer_id: f for f in store.fingerprints(view_id=view.view_id)}
        self.text_fp, self.dom_fp = fps.get("text.shingle"), fps.get("kit.dom")
        self.text = body_text(self.obs)
        self.tag_paths = _list_values(self.obs, "dom.tag_paths")
        self.classes = _list_values(self.obs, "dom.class_set") | _list_values(self.obs, "dom.class")
        self.host = _registrable(self.obs)
        self.trackers = _trackers(self.obs)

    @property
    def loaded(self) -> bool:
        """A page was saved. A timeout that still rendered one counts: it can be compared."""
        return self.view.primary is not None

    @property
    def mobile(self) -> bool:
        return "Mobile" in self.user_agent or "Android" in self.user_agent

    @property
    def bot(self) -> bool:
        return "bot" in self.user_agent.lower()

    @property
    def hash_class_share(self) -> float:
        if not self.classes:
            return 0.0
        return round(sum(is_hash_like(c) for c in self.classes) / len(self.classes), 3)


# --- the comparison ---------------------------------------------------------------------


def compare_variants(ref: _Variant, other: _Variant) -> dict[str, Any]:
    """The J1 value for one pair; `difference` is None when it cannot be measured."""
    value: dict[str, Any] = {
        "reference": ref.profile,
        "against": other.profile,
        "against_view": other.view.view_id,
        "threshold": THRESHOLD,
    }
    if not (ref.loaded and other.loaded):
        value["difference"] = None
        value["not_loaded"] = {v.profile: v.status for v in (ref, other) if not v.loaded}
        return value
    text_sim = text_similarity(ref.text, other.text, ref.text_fp, other.text_fp)
    structure = [s for s in (jaccard(ref.tag_paths, other.tag_paths),) if s is not None]
    if ref.dom_fp is not None and other.dom_fp is not None:
        structure.append(comparators.get("minhash").compare(ref.dom_fp, other.dom_fp).score)
    hosts_differ = bool(ref.host and other.host and ref.host != other.host)
    value.update(
        difference=difference_score(text_sim, structure, hosts_differ),
        text_similarity=None if text_sim is None else round(text_sim, 3),
        structure_similarity=round(sum(structure) / len(structure), 3) if structure else None,
        final_hosts={ref.profile: ref.host, other.profile: other.host},
        statuses={ref.profile: ref.status, other.profile: other.status},
    )
    if other.status == "http_error":
        value["caveat"] = (
            f"{other.profile} got an HTTP error: the page may need its query to exist, "
            "so the difference is not by itself gating"
        )
    return value


def gating_factors(ref: _Variant, other: _Variant) -> list[str]:
    """What the ad-click capture carried that the other did not, as each manifest recorded."""
    factors: list[str] = []
    if ref.referer and ref.referer != other.referer:
        factors.append(f"referrer {ref.referer}")
    ref_query, other_query = urlsplit(ref.url).query, urlsplit(other.url).query
    if ref_query and ref_query != other_query:
        original = ref_query
        if ref.click_id_added:
            original = ref_query.removesuffix(f"fbclid={SYNTHETIC_FBCLID}").removesuffix("&")
        if ref.click_id_added and not original:
            factors.append("click id (synthetic fbclid)")
        elif ref.click_id_added:
            factors.append("query string and a click id (synthetic fbclid)")
        else:
            factors.append("query string")
    if ref.mobile and not other.mobile:
        factors.append("mobile device")
    if other.bot and not ref.bot:
        factors.append("regular browser user agent")
    return factors


def _white_page(ref: _Variant, other: _Variant) -> dict[str, Any] | None:
    traits = []
    if ref.trackers and not other.trackers:
        traits.append("no trackers, while the ad click loads them")
    share = other.hash_class_share
    if share >= HASH_CLASS_SHARE and share >= ref.hash_class_share + HASH_CLASS_MARGIN:
        traits.append(f"obfuscated class names ({share:.0%} hash-like)")
    if not traits:
        return None
    return {
        "against": ref.profile,
        "traits": traits,
        "hash_like_class_share": share,
        "trackers_here": other.trackers,
        "trackers_on_reference": ref.trackers,
    }


def _obs(view: View, signal: str, namespace: str, value, state: State, raw: str) -> Observation:
    return Observation(
        view_id=view.view_id,
        signal_id=signal,
        namespace=namespace,
        value=value,
        raw=raw,
        state=state,
        purpose=Purpose.RISK,
        source=Source(file="differential.json", locator=f"profile:{value.get('against')}"),
        extractor=EXTRACTOR,
        version=VERSION,
    )


def differential_observations(variants: list[_Variant]) -> dict[str, list[Observation]]:
    """Observations per view id for the variants of one tested URL."""
    out: dict[str, list[Observation]] = {v.view.view_id: [] for v in variants}
    ref = next((v for v in variants if v.profile == REFERENCE), None)
    if ref is None:
        return out
    for other in (v for v in variants if v is not ref):
        pair = compare_variants(ref, other)
        diff = pair["difference"]
        if diff is None:
            reason = pair.get("not_loaded") or "nothing comparable on either variant"
            out[ref.view.view_id].append(
                _obs(
                    ref.view,
                    "J1",
                    "cloak.differential",
                    pair,
                    State.NOT_OBSERVABLE,
                    f"{ref.profile} vs {other.profile}: not comparable ({reason})",
                )
            )
            continue
        cloaked = diff >= THRESHOLD
        summary = f"{ref.profile} vs {other.profile}: difference {diff:.2f}"
        if pair.get("caveat"):
            summary += f" ({other.profile}: HTTP error)"
        out[ref.view.view_id].append(
            _obs(
                ref.view,
                "J1",
                "cloak.differential",
                pair,
                State.PRESENT if cloaked else State.ABSENT,
                summary,
            )
        )
        if not cloaked:
            continue
        if other.profile == "bare" and other.status != "http_error":
            factors = gating_factors(ref, other)
            gate = {"against": other.profile, "difference": diff, "factors": factors}
            out[ref.view.view_id].append(
                _obs(
                    ref.view,
                    "J5",
                    "cloak.gating",
                    gate,
                    State.PRESENT,
                    "offer shown only with: " + ", ".join(factors or ["the ad-click profile"]),
                )
            )
        white = _white_page(ref, other)
        if white is not None:
            out[other.view.view_id].append(
                _obs(
                    other.view,
                    "J2",
                    "cloak.white_page",
                    white,
                    State.PRESENT,
                    "; ".join(white["traits"]),
                )
            )
    return out


def _run_key(view: View) -> tuple[str, ...]:
    """The run a variant belongs to. Bundles without a run id (written before it existed)
    fall back to the URL and the folder holding the profile bundles."""
    run = view.meta.get("capture_run")
    if run:
        return (view.incident_id, str(run))
    file = view.primary or next(iter(view.attachments), "")
    folder = str(PurePosixPath(file).parent.parent)
    return (view.incident_id, str(view.meta["capture_differential"]), folder)


def run_cloaking(store: Store) -> int:
    """Compare the variants of every tested URL; replaces earlier rows. Returns rows written."""
    load_plugins()
    groups: dict[tuple[str, ...], list[View]] = {}
    for view in store.views():
        if view.meta.get("capture_differential"):
            groups.setdefault(_run_key(view), []).append(view)
    count = 0
    for views in groups.values():
        found = differential_observations([_Variant(store, v) for v in views])
        for view_id, rows in found.items():
            store.put_observations(view_id, EXTRACTOR, rows)
            count += len(rows)
    return count
